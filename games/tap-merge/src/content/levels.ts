// Journey and Daily content (SPEC.md, "Hành Trình" and "Mỗi Ngày"). The level table is generated from real runs by
// `scripts/levels.ts` and checked in as `levels.data.ts`; this file holds the types, the chapters and the star rules.
import { DAILY_TAPS, type Exponent, type LevelStart, type State } from '../logic.ts';
import { LEVELS_DATA } from './levels.data.ts';

export interface Chapter {
  readonly id: string;
  readonly number: number;
  readonly vi: string;
  readonly en: string;
  /** How many levels must be complete in the earlier chapters before this one opens. */
  readonly unlockAt: number;
}

export const CHAPTERS: readonly Chapter[] = [
  { id: 'mam', number: 1, vi: 'Mầm', en: 'Sprout', unlockAt: 0 },
  { id: 'choi', number: 2, vi: 'Chồi', en: 'Shoot', unlockAt: 6 },
  { id: 'la', number: 3, vi: 'Lá', en: 'Leaf', unlockAt: 6 },
];

export interface Par {
  /** Taps for three stars; the level is still complete after this, for one star. */
  readonly three: number;
  readonly two: number;
}

export interface Level extends LevelStart {
  readonly chapter: number;
  readonly index: number;
  /** The exponent to make; the level completes when `top` reaches it. */
  readonly target: Exponent;
  readonly par: Par;
  readonly intro: { readonly vi: string; readonly en: string };
}

/** Generated by `scripts/levels.ts`; the numbers are snapshots of real runs, not hand-tuned boards. */
export const LEVELS: readonly Level[] = LEVELS_DATA as readonly Level[];

export const LEVEL_BY_ID: ReadonlyMap<string, Level> = new Map(LEVELS.map((level) => [level.id, level]));

export const chapterLevels = (chapter: number): readonly Level[] =>
  LEVELS.filter((level) => level.chapter === chapter);

export const chapterOf = (level: Level): Chapter =>
  CHAPTERS.find((chapter) => chapter.number === level.chapter) ?? (CHAPTERS[0] as Chapter);

export const nextLevel = (level: Level): Level | null =>
  LEVELS.find((item) => item.chapter === level.chapter && item.index === level.index + 1) ?? null;

/** A level is complete when the target block has been made. */
export const levelComplete = (state: State, level: Level): boolean => state.top >= level.target;

/** 1 star for completing; 2/3 when the level is finished within its par. */
export function levelStars(state: State, level: Level): 0 | 1 | 2 | 3 {
  if (!levelComplete(state, level)) return 0;
  if (state.moves <= level.par.three) return 3;
  if (state.moves <= level.par.two) return 2;
  return 1;
}

/** Number of completed levels (at least one star) in the journey map. */
export const completedLevels = (journey: Readonly<Record<string, number>>): number =>
  Object.values(journey).filter((stars) => stars > 0).length;

/** A chapter opens when the chapter before it holds `unlockAt` completed levels (six of eight). */
export const chapterUnlocked = (chapter: Chapter, journey: Readonly<Record<string, number>>): boolean => {
  if (chapter.number <= 1) return true;
  const previous = CHAPTERS.find((item) => item.number === chapter.number - 1);
  if (!previous) return false;
  const done = chapterLevels(previous.number).filter((level) => (journey[level.id] ?? 0) > 0).length;
  return done >= chapter.unlockAt;
};

/** The next level to play: the first uncompleted one in an open chapter. */
export function nextJourneyLevel(journey: Readonly<Record<string, number>>): Level {
  for (const chapter of CHAPTERS) {
    if (!chapterUnlocked(chapter, journey)) continue;
    const level = chapterLevels(chapter.number).find((item) => (journey[item.id] ?? 0) === 0);
    if (level) return level;
  }
  return LEVELS[0] as Level;
}

/** Daily stars: 1K / 2K / 4K. The first star is deliberately easy. */
export const DAILY_TARGET: Exponent = 12;
export const dailyStars = (top: Exponent): 0 | 1 | 2 | 3 =>
  top >= 12 ? 3 : top >= 11 ? 2 : top >= 10 ? 1 : 0;

/** The date-seeded daily board: the same date gives the same board to everyone. */
export function dailySeed(date: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < date.length; i++) {
    hash ^= date.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

export const dailyLevelId = (date: string): string => `daily-${date}`;

/** The daily's tap budget, shared with the screen copy. */
export const dailyMoves = DAILY_TAPS;

/** Whether a daily run is over: the budget is spent or the board is stuck. */
export const dailyDone = (state: State): boolean => state.over || state.moves >= dailyMoves;
