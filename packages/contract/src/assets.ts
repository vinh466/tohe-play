import { z } from 'zod';
import { GameId, SemVer } from './ids.ts';

/**
 * Assets in the Game Contract (ADR 0053): the packs a game declares in `game.json`, the lock that pins every file by
 * hash, and the credits. A build of a game with `assets` carries the folder `studio/`: every file it uses named
 * `<sha256>.<ext>`, `lock.json` (a copy of the game's `assets.lock.json`) and `credits.json`.
 */

/** A pack's id: the same rule as a game's (`a-z`, digits, `-`; 3–40). */
export const PackId = GameId;
export type PackId = z.infer<typeof PackId>;

/** How a pack reaches the device (ADR 0051): only `bundle` — in the build — for now. */
export const ASSET_DELIVERIES = ['bundle'] as const;
export const AssetDelivery = z.enum(ASSET_DELIVERIES);
export type AssetDelivery = z.infer<typeof AssetDelivery>;

/** Most packs a game declares. */
export const MAX_ASSET_PACKS = 20;

/** One pack a game uses: an exact version (never a range), how it is delivered, and optionally which assets. */
export const AssetPackRef = z
  .object({
    version: SemVer.describe('The pack version, exact semver — never a range'),
    delivery: AssetDelivery.describe('How the pack reaches the device; only "bundle" for now (ADR 0051)'),
    include: z
      .array(z.string().min(1).max(100))
      .min(1)
      .max(50)
      .optional()
      .describe('Globs of asset ids to take from the pack; without it, the whole pack'),
  })
  .strict();
export type AssetPackRef = z.infer<typeof AssetPackRef>;

/** `game.json`'s `assets`: a pack id → the pack it pins, at most 20 (ADR 0053). */
export const GameAssets = z
  .record(PackId, AssetPackRef)
  .refine((packs) => Object.keys(packs).length <= MAX_ASSET_PACKS, `at most ${MAX_ASSET_PACKS} packs`);
export type GameAssets = z.infer<typeof GameAssets>;

/**
 * The licences the Studio accepts (ADR 0051), as SPDX identifiers. `LicenseRef-Tohe-Internal` is for what is made for
 * Tò He, until the repository chooses a licence.
 */
export const ACCEPTED_ASSET_LICENCES = [
  'CC0-1.0',
  'CC-BY-4.0',
  'CC-BY-SA-4.0',
  'OFL-1.1',
  'MIT',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  'LicenseRef-Tohe-Internal',
] as const;
export type AcceptedAssetLicence = (typeof ACCEPTED_ASSET_LICENCES)[number];

const NO_ATTRIBUTION: readonly string[] = ['CC0-1.0', 'LicenseRef-Tohe-Internal'];

/** Whether a file under this licence must be credited: every licence but `CC0-1.0` and `LicenseRef-Tohe-Internal`. */
export const licenceNeedsAttribution = (spdx: string) => !NO_ATTRIBUTION.includes(spdx);

/** An SPDX licence identifier as the lock holds it; whether the Studio accepts it is conformance's check. */
const SpdxId = z
  .string()
  .regex(/^[A-Za-z0-9][A-Za-z0-9.+-]{0,63}$/, 'an SPDX licence identifier, e.g. CC0-1.0');

/** An asset's id in its pack: `a-z`, digits, `-`, and `/` for folders (`crops/carrot`). */
export const AssetId = z
  .string()
  .max(100)
  .regex(/^[a-z0-9][a-z0-9-]*(?:\/[a-z0-9][a-z0-9-]*)*$/, 'a-z, digits, - and / for folders');

/** The kinds of asset (ADR 0051). */
export const AssetKind = z.enum(['image', 'spritesheet', 'tileset', 'audio', 'font', 'palette']);
export type AssetKind = z.infer<typeof AssetKind>;

const Sha256 = z.string().regex(/^[0-9a-f]{64}$/, 'a sha256 in lowercase hex');
const FileExtension = z.string().regex(/^[a-z0-9]{1,8}$/, 'a file extension without the dot, e.g. png');

/** One file of a pack, pinned by the lock. */
export const LockedAssetFile = z
  .object({
    id: AssetId,
    kind: AssetKind,
    sha256: Sha256,
    ext: FileExtension,
    bytes: z.number().int().nonnegative(),
    licence: SpdxId,
    attribution: z.string().min(1).max(1000).optional(),
  })
  .strict();
export type LockedAssetFile = z.infer<typeof LockedAssetFile>;

/** One pack in the lock: its version, the sha256 of its Studio manifest, and its files. */
export const LockedAssetPack = z
  .object({
    version: SemVer,
    manifest: Sha256.describe("The sha256 of the pack version's manifest in the Studio"),
    files: z.array(LockedAssetFile),
  })
  .strict()
  .superRefine((pack, context) => {
    const ids = new Set<string>();
    pack.files.forEach((file, index) => {
      if (ids.has(file.id))
        context.addIssue({ code: 'custom', path: ['files', index, 'id'], message: 'repeated id' });
      ids.add(file.id);
    });
  });
export type LockedAssetPack = z.infer<typeof LockedAssetPack>;

/** `assets.lock.json`, in the game's folder next to its package.json, generated by `pnpm assets:resolve`; the build copies it to `studio/lock.json`. */
export const AssetsLock = z
  .object({
    lockVersion: z.literal(1),
    packs: z.record(PackId, LockedAssetPack),
  })
  .strict();
export type AssetsLock = z.infer<typeof AssetsLock>;

/** `studio/credits.json`: every pack with its licences and, for every file whose licence asks for it, the attribution. */
export const AssetCredits = z
  .object({
    packs: z.array(
      z
        .object({
          id: PackId,
          version: SemVer,
          licences: z.array(SpdxId),
          attributions: z.array(
            z.object({ assets: z.array(AssetId).min(1), text: z.string().min(1).max(1000) }).strict(),
          ),
        })
        .strict(),
    ),
  })
  .strict();
export type AssetCredits = z.infer<typeof AssetCredits>;

/** The build's folder for assets, and its two files (ADR 0053). */
export const STUDIO_DIR = 'studio';
export const STUDIO_LOCK = `${STUDIO_DIR}/lock.json`;
export const STUDIO_CREDITS = `${STUDIO_DIR}/credits.json`;

/** A file's name in `studio/`: its hash and its extension. */
export const studioFileName = (file: Pick<LockedAssetFile, 'sha256' | 'ext'>) => `${file.sha256}.${file.ext}`;

// ------------------------------------------------------------------------------------------------ conformance checks
// Pure, so conformance and the build tool share them; each returns what is wrong, one line each, or nothing.

/** Check 1: the lock's packs and versions are exactly those of `assets`. */
export function lockMatchesAssets(assets: GameAssets, lock: AssetsLock): string[] {
  const problems: string[] = [];
  for (const [id, ref] of Object.entries(assets)) {
    const locked = lock.packs[id];
    if (!locked) problems.push(`${id}@${ref.version}: declared, not in the lock`);
    else if (locked.version !== ref.version)
      problems.push(`${id}: declared ${ref.version}, locked ${locked.version}`);
  }
  for (const [id, locked] of Object.entries(lock.packs)) {
    if (!(id in assets)) problems.push(`${id}@${locked.version}: in the lock, not declared`);
  }
  return problems;
}

/** A file found in `studio/` (not `lock.json` or `credits.json`): its name, and the sha256 of its content (null for a folder). */
export interface StudioEntry {
  name: string;
  sha256: string | null;
}

const STUDIO_FILE = /^([0-9a-f]{64})\.([a-z0-9]{1,8})$/;

/** Check 2: every file in `studio/` is in the lock with the same sha256, and every file in the lock is in `studio/`. */
export function studioMatchesLock(lock: AssetsLock, entries: readonly StudioEntry[]): string[] {
  const problems: string[] = [];
  const locked = new Set(Object.values(lock.packs).flatMap((pack) => pack.files.map(studioFileName)));
  const found = new Set<string>();
  for (const entry of entries) {
    const named = STUDIO_FILE.exec(entry.name);
    if (!named || entry.sha256 === null) {
      problems.push(`${STUDIO_DIR}/${entry.name}: not a file named <sha256>.<ext>`);
      continue;
    }
    if (named[1] !== entry.sha256) {
      problems.push(`${STUDIO_DIR}/${entry.name}: its content hashes to ${entry.sha256}`);
      continue;
    }
    if (!locked.has(entry.name)) problems.push(`${STUDIO_DIR}/${entry.name}: not in the lock`);
    found.add(entry.name);
  }
  for (const [id, pack] of Object.entries(lock.packs)) {
    for (const file of pack.files) {
      const name = studioFileName(file);
      if (!found.has(name)) problems.push(`${id}/${file.id}: ${STUDIO_DIR}/${name} is missing`);
    }
  }
  return problems;
}

/**
 * Check 3: every licence in the lock is one the Studio accepts, a file whose licence asks for credit has an
 * attribution, and `credits.json` lists every pack of the lock with its licences and every attribution the lock holds.
 */
export function creditsCoverLock(lock: AssetsLock, credits: AssetCredits): string[] {
  const problems: string[] = [];
  const accepted: readonly string[] = ACCEPTED_ASSET_LICENCES;
  for (const [id, pack] of Object.entries(lock.packs)) {
    const credited = credits.packs.find((entry) => entry.id === id && entry.version === pack.version);
    if (!credited) problems.push(`${id}@${pack.version}: not in ${STUDIO_CREDITS}`);
    for (const file of pack.files) {
      const where = `${id}/${file.id}`;
      if (!accepted.includes(file.licence))
        problems.push(`${where}: ${file.licence} is not an accepted licence`);
      if (credited && !credited.licences.includes(file.licence))
        problems.push(`${where}: ${file.licence} is not among the pack's licences in ${STUDIO_CREDITS}`);
      if (file.attribution === undefined) {
        if (licenceNeedsAttribution(file.licence))
          problems.push(`${where}: ${file.licence} needs an attribution`);
        continue;
      }
      const named = credited?.attributions.some(
        (attribution) => attribution.text === file.attribution && attribution.assets.includes(file.id),
      );
      if (credited && !named) problems.push(`${where}: its attribution is not in ${STUDIO_CREDITS}`);
    }
  }
  for (const entry of credits.packs) {
    if (lock.packs[entry.id]?.version !== entry.version)
      problems.push(`${entry.id}@${entry.version}: in ${STUDIO_CREDITS}, not in the lock`);
  }
  return problems;
}
