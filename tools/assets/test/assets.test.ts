import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { AssetCredits, AssetsLock, creditsCoverLock, STUDIO_DIR, studioMatchesLock } from '@tohe/contract';
import { build } from 'vite';
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { checkGame } from '../src/check.ts';
import { gameFolder } from '../src/game.ts';
import { camelCase } from '../src/generate.ts';
import { defaultCacheDir, resolveOptions } from '../src/options.ts';
import { resolveGame } from '../src/resolve.ts';
import { studioOutputs } from '../src/studio.ts';
import { toheAssets } from '../src/vite.ts';
import { type FixtureRegistry, type FixtureWorkspace, makeWorkspace, startRegistry } from './fixtures.ts';

const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

const carrot = {
  id: 'crops/carrot',
  kind: 'spritesheet',
  ext: 'png',
  content: 'carrot pixels',
  licence: 'CC-BY-4.0',
  attribution: 'Carrot by Ann',
  width: 64,
  height: 16,
  frames: { width: 16, height: 16, count: 4 },
} as const;
const wheat = {
  id: 'crops/wheat',
  kind: 'image',
  ext: 'png',
  content: 'wheat pixels',
  licence: 'CC0-1.0',
  width: 16,
  height: 16,
} as const;
const click = {
  id: 'ui/click',
  kind: 'audio',
  ext: 'ogg',
  content: 'click sound',
  licence: 'CC-BY-4.0',
  attribution: 'Sounds by Bo',
} as const;
const tile = (id: string) =>
  ({
    id,
    kind: 'image',
    ext: 'png',
    content: `${id} pixels`,
    licence: 'MIT',
    attribution: 'Tiles by Cy',
  }) as const;

let registry: FixtureRegistry;
let workspace: FixtureWorkspace;
let options: { registry: string; cacheDir: string; offline?: boolean };

beforeAll(async () => {
  registry = await startRegistry({
    'farm-crops': {
      '1.0.0': [wheat, carrot, click],
      '1.1.0': [wheat, carrot, click, { ...wheat, id: 'crops/corn', content: 'corn pixels' }],
    },
    'farm-tiles': {
      '2.1.0': [tile('ground/grass'), tile('ground/dirt'), tile('fence/post'), tile('water/sea')],
    },
    'odd-licence': { '1.0.0': [{ ...wheat, licence: 'CC-BY-NC-4.0' }] },
  });
});
afterAll(() => registry.close());

beforeEach(() => {
  workspace = makeWorkspace();
  options = { registry: registry.url, cacheDir: workspace.cache };
  registry.requests.length = 0;
  registry.failures.clear();
  registry.overrides.clear();
});
afterEach(() => workspace.cleanup());

const game = () => gameFolder(workspace.game, workspace.root);
const declareFarm = () =>
  workspace.declare({
    'farm-tiles': { version: '2.1.0', delivery: 'bundle', include: ['ground/*', 'fence/*'] },
    'farm-crops': { version: '1.0.0', delivery: 'bundle' },
  });
const readLockFile = () =>
  AssetsLock.parse(JSON.parse(readFileSync(join(workspace.game, 'assets.lock.json'), 'utf8')));
const generated = () => readFileSync(join(workspace.game, 'src/assets.gen.ts'), 'utf8');

describe('resolve', () => {
  it('writes the lock, pinning each manifest by hash and taking only what include selects', async () => {
    declareFarm();
    const result = await resolveGame(game(), options);
    expect(result).toMatchObject({ packs: 2, files: 6 });

    const lock = readLockFile();
    expect(Object.keys(lock.packs)).toEqual(['farm-crops', 'farm-tiles']);
    expect(lock.packs['farm-crops']?.manifest).toBe(registry.manifest('farm-crops', '1.0.0').sha256);
    expect(lock.packs['farm-tiles']?.files.map((file) => file.id)).toEqual([
      'fence/post',
      'ground/dirt',
      'ground/grass',
    ]);
    expect(lock.packs['farm-crops']?.files[0]).toEqual({
      id: 'crops/carrot',
      kind: 'spritesheet',
      sha256: registry.file('farm-crops', '1.0.0', 'crops/carrot').sha256,
      ext: 'png',
      bytes: carrot.content.length,
      licence: 'CC-BY-4.0',
      attribution: 'Carrot by Ann',
    });
  });

  it('writes a typed module whose URLs are relative to the build', async () => {
    declareFarm();
    await resolveGame(game(), options);
    const text = generated();
    const carrotHash = registry.file('farm-crops', '1.0.0', 'crops/carrot').sha256;
    expect(text).toMatch(/^\/\/ Generated by `pnpm assets:resolve`/);
    expect(text).toContain(`  farmCrops: {
    'crops/carrot': {
      key: 'farm-crops/crops/carrot',
      url: './${STUDIO_DIR}/${carrotHash}.png',
      kind: 'spritesheet',
      width: 64,
      height: 16,
      frames: { width: 16, height: 16, count: 4 },
    },`);
    expect(text).toContain("  farmTiles: {\n    'fence/post': {");
    expect(text).not.toContain('water/sea');
  });

  it('gives the same bytes every time, and leaves unchanged files alone', async () => {
    declareFarm();
    await resolveGame(game(), options);
    const [lock, typed] = [readFileSync(join(workspace.game, 'assets.lock.json')), generated()];
    const again = await resolveGame(game(), options);
    expect(again.changed).toEqual([]);
    expect(readFileSync(join(workspace.game, 'assets.lock.json'))).toEqual(lock);
    expect(generated()).toBe(typed);
  });

  it('fails naming the variable when no registry is set', async () => {
    declareFarm();
    await expect(resolveGame(game(), { cacheDir: workspace.cache, registry: '' })).rejects.toThrow(
      'TOHE_ASSETS_REGISTRY',
    );
  });

  it('fails naming the pack and version when the version has no manifest (withdrawn)', async () => {
    workspace.declare({ 'farm-crops': { version: '9.0.0', delivery: 'bundle' } });
    await expect(resolveGame(game(), options)).rejects.toThrow(
      /farm-crops@9\.0\.0: the registry has no manifest/,
    );
    expect(existsSync(join(workspace.game, 'assets.lock.json'))).toBe(false);
  });

  it('fails on a glob that matches nothing, and on a licence the Studio does not accept', async () => {
    workspace.declare({ 'farm-tiles': { version: '2.1.0', delivery: 'bundle', include: ['grond/*'] } });
    await expect(resolveGame(game(), options)).rejects.toThrow('"grond/*" matches no asset');
    workspace.declare({ 'odd-licence': { version: '1.0.0', delivery: 'bundle' } });
    await expect(resolveGame(game(), options)).rejects.toThrow('CC-BY-NC-4.0 is not an accepted licence');
  });

  it('removes the lock and the typed module of a game that no longer declares assets', async () => {
    declareFarm();
    await resolveGame(game(), options);
    workspace.declare(undefined);
    const result = await resolveGame(game(), options);
    expect(result.changed).toHaveLength(2);
    expect(existsSync(join(workspace.game, 'assets.lock.json'))).toBe(false);
    expect(existsSync(join(workspace.game, 'src/assets.gen.ts'))).toBe(false);
  });
});

/** studio/ as a build wrote it, checked the way conformance checks it. */
function readStudio(dist: string) {
  const dir = join(dist, STUDIO_DIR);
  const entries = readdirSync(dir)
    .filter((name) => name !== 'lock.json' && name !== 'credits.json')
    .map((name) => ({ name, sha256: sha256(readFileSync(join(dir, name))) }));
  const lock = AssetsLock.parse(JSON.parse(readFileSync(join(dir, 'lock.json'), 'utf8')));
  const credits = AssetCredits.parse(JSON.parse(readFileSync(join(dir, 'credits.json'), 'utf8')));
  return { dir, entries, lock, credits };
}

const viteBuild = (plugin = toheAssets(options)) =>
  build({
    root: workspace.game,
    configFile: false,
    logLevel: 'silent',
    base: './',
    plugins: [plugin],
    build: { outDir: join(workspace.game, 'dist'), emptyOutDir: true },
  });

describe('the build', () => {
  it('ships every locked file by hash, a copy of the lock and the credits, and passes conformance', async () => {
    declareFarm();
    await resolveGame(game(), options);
    await viteBuild();
    const studio = readStudio(join(workspace.game, 'dist'));
    expect(studio.entries).toHaveLength(6);
    expect(studioMatchesLock(studio.lock, studio.entries)).toEqual([]);
    expect(creditsCoverLock(studio.lock, studio.credits)).toEqual([]);
    expect(readFileSync(join(studio.dir, 'lock.json'), 'utf8')).toBe(
      readFileSync(join(workspace.game, 'assets.lock.json'), 'utf8'),
    );
    const carrotFile = registry.file('farm-crops', '1.0.0', 'crops/carrot');
    expect(readFileSync(join(studio.dir, `${carrotFile.sha256}.png`))).toEqual(carrotFile.bytes);
    expect(studio.credits.packs).toEqual([
      {
        id: 'farm-crops',
        version: '1.0.0',
        licences: ['CC-BY-4.0', 'CC0-1.0'],
        attributions: [
          { assets: ['crops/carrot'], text: 'Carrot by Ann' },
          { assets: ['ui/click'], text: 'Sounds by Bo' },
        ],
      },
      {
        id: 'farm-tiles',
        version: '2.1.0',
        licences: ['MIT'],
        attributions: [{ assets: ['fence/post', 'ground/dirt', 'ground/grass'], text: 'Tiles by Cy' }],
      },
    ]);
  });

  it('reads only the lock: the manifests are not fetched again, and the files come from the cache', async () => {
    declareFarm();
    await resolveGame(game(), options);
    registry.requests.length = 0;
    await studioOutputs(game(), options);
    expect(registry.requests.every((path) => path.startsWith('/blobs/sha256/'))).toBe(true);
    expect(registry.requests).toHaveLength(6);
    registry.requests.length = 0;
    await studioOutputs(game(), options);
    expect(registry.requests).toEqual([]);
  });

  it('fails, asking to resolve, when the lock is not that of game.json', async () => {
    declareFarm();
    await resolveGame(game(), options);
    workspace.declare({ 'farm-crops': { version: '1.1.0', delivery: 'bundle' } });
    await expect(viteBuild()).rejects.toThrow(
      /run pnpm assets:resolve[\s\S]*farm-crops: declared 1\.1\.0, locked 1\.0\.0/,
    );
  });

  it('fails without a lock', async () => {
    declareFarm();
    await expect(studioOutputs(game(), options)).rejects.toThrow(
      'no assets.lock.json — run pnpm assets:resolve',
    );
  });

  it('offline, never fetches: it fails naming every missing file, and works from a warm cache', async () => {
    declareFarm();
    await resolveGame(game(), options);
    registry.requests.length = 0;
    const offline = { ...options, offline: true };
    const error = await studioOutputs(game(), offline).catch((caught: Error) => caught);
    expect(error).toBeInstanceOf(Error);
    for (const id of [
      'farm-crops/crops/carrot',
      'farm-crops/crops/wheat',
      'farm-crops/ui/click',
      'farm-tiles/fence/post',
    ])
      expect((error as Error).message).toContain(id);
    expect((error as Error).message).toContain('6 file(s) are not in the cache');
    expect(registry.requests).toEqual([]);

    await studioOutputs(game(), options);
    registry.requests.length = 0;
    const outputs = await studioOutputs(game(), offline);
    expect(outputs).toHaveLength(8);
    expect(registry.requests).toEqual([]);
  });

  it('fails on a cached file whose content does not hash to its name', async () => {
    declareFarm();
    await resolveGame(game(), options);
    await studioOutputs(game(), options);
    const wheatFile = registry.file('farm-crops', '1.0.0', 'crops/wheat');
    const cached = join(workspace.cache, `${wheatFile.sha256}.png`);
    writeFileSync(cached, 'tampered');
    await expect(studioOutputs(game(), options)).rejects.toThrow(
      `farm-crops/crops/wheat: ${cached} in the cache hashes to ${sha256(Buffer.from('tampered'))}`,
    );
  });

  it('fails on a download whose content does not hash to what the lock pins, and keeps it out of the cache', async () => {
    declareFarm();
    await resolveGame(game(), options);
    const wheatFile = registry.file('farm-crops', '1.0.0', 'crops/wheat');
    registry.overrides.set(wheatFile.path, Buffer.from('not wheat'));
    await expect(studioOutputs(game(), options)).rejects.toThrow(
      `farm-crops/crops/wheat: ${registry.url}blobs/sha256/${wheatFile.sha256}.png hashes to`,
    );
    expect(existsSync(join(workspace.cache, `${wheatFile.sha256}.png`))).toBe(false);
  });

  it('fails naming the file and the URL when a download fails', async () => {
    declareFarm();
    await resolveGame(game(), options);
    const clickFile = registry.file('farm-crops', '1.0.0', 'ui/click');
    registry.failures.set(clickFile.path, 503);
    await expect(studioOutputs(game(), options)).rejects.toThrow(
      `farm-crops/ui/click: ${registry.url}blobs/sha256/${clickFile.sha256}.ogg answered 503`,
    );
    registry.failures.set(clickFile.path, 404);
    await expect(studioOutputs(game(), options)).rejects.toThrow(
      `farm-crops/ui/click: the registry has no file at ${registry.url}blobs/sha256/${clickFile.sha256}.ogg`,
    );
  });

  it('fails naming the variable when a file must be fetched and no registry is set', async () => {
    declareFarm();
    await resolveGame(game(), options);
    await expect(studioOutputs(game(), { cacheDir: workspace.cache, registry: '' })).rejects.toThrow(
      'set TOHE_ASSETS_REGISTRY',
    );
  });

  it('leaves a game without assets as it was', async () => {
    await viteBuild();
    expect(existsSync(join(workspace.game, 'dist', STUDIO_DIR))).toBe(false);
    expect(existsSync(join(workspace.game, 'dist', 'index.html'))).toBe(true);
    expect(registry.requests).toEqual([]);
  });
});

describe('the drift check', () => {
  it('passes for what resolve wrote, from the cache and offline', async () => {
    declareFarm();
    await resolveGame(game(), options);
    registry.requests.length = 0;
    expect(await checkGame(game(), { ...options, offline: true })).toEqual([]);
    expect(registry.requests).toEqual([]);
  });

  it('fetches a pinned manifest missing from the cache, and checks its hash', async () => {
    declareFarm();
    await resolveGame(game(), options);
    const otherCache = join(workspace.root, 'other-cache');
    expect(await checkGame(game(), { ...options, cacheDir: otherCache })).toEqual([]);
    registry.overrides.set('/packs/farm-crops/1.0.0.json', Buffer.from('{"changed":true}'));
    await expect(checkGame(game(), { ...options, cacheDir: join(workspace.root, 'third') })).rejects.toThrow(
      /farm-crops@1\.0\.0: .*packs\/farm-crops\/1\.0\.0\.json hashes to/,
    );
  });

  it('finds a typed module edited by hand', async () => {
    declareFarm();
    await resolveGame(game(), options);
    writeFileSync(join(workspace.game, 'src/assets.gen.ts'), `${generated()}// edited\n`);
    expect(await checkGame(game(), options)).toEqual([
      'src/assets.gen.ts is not what assets.lock.json generates',
      'run pnpm assets:resolve, and commit both files',
    ]);
  });

  it('finds a lock that no longer matches game.json', async () => {
    declareFarm();
    await resolveGame(game(), options);
    workspace.declare({
      'farm-tiles': { version: '2.1.0', delivery: 'bundle', include: ['ground/*'] },
      'farm-crops': { version: '1.0.0', delivery: 'bundle' },
    });
    expect(await checkGame(game(), options)).toContain(
      "assets.lock.json is not what game.json's assets and the manifests it pins make",
    );
    workspace.declare({ 'farm-crops': { version: '1.1.0', delivery: 'bundle' } });
    expect(await checkGame(game(), options)).toEqual([
      'assets.lock.json: farm-crops: declared 1.1.0, locked 1.0.0',
      'assets.lock.json: farm-tiles@2.1.0: in the lock, not declared',
    ]);
  });

  it('finds a missing lock or typed module, and leftovers in a game without assets', async () => {
    declareFarm();
    expect(await checkGame(game(), options)).toEqual(['game: no assets.lock.json — run pnpm assets:resolve']);
    await resolveGame(game(), options);
    workspace.declare(undefined);
    expect(await checkGame(game(), options)).toEqual([
      'assets.lock.json exists, but game.json declares no assets',
      'src/assets.gen.ts exists, but game.json declares no assets',
    ]);
  });

  it('passes for a game without assets', async () => {
    expect(await checkGame(game(), options)).toEqual([]);
  });
});

describe('options and names', () => {
  it('keeps the cache under XDG_CACHE_HOME, else ~/.cache', () => {
    expect(defaultCacheDir({ XDG_CACHE_HOME: '/x' })).toBe('/x/tohe/assets/sha256');
    expect(defaultCacheDir({})).toMatch(/\.cache\/tohe\/assets\/sha256$/);
    expect(
      resolveOptions({}, { TOHE_ASSETS_OFFLINE: '1', TOHE_ASSETS_REGISTRY: 'https://r.test' }),
    ).toMatchObject({
      offline: true,
      registry: 'https://r.test',
    });
  });

  it('names packs in camelCase', () => {
    expect(camelCase('farm-crops')).toBe('farmCrops');
    expect(camelCase('ui-2d-icons')).toBe('ui2dIcons');
  });
});

it('creates src/ when the game has none yet', async () => {
  workspace.declare({ 'farm-crops': { version: '1.0.0', delivery: 'bundle' } });
  rmSync(join(workspace.game, 'src'), { recursive: true });
  await resolveGame(game(), options);
  expect(existsSync(join(workspace.game, 'src/assets.gen.ts'))).toBe(true);
});
